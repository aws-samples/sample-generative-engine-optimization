import { CfnOutput, Stack } from 'aws-cdk-lib';
import type * as lambda from 'aws-cdk-lib/aws-lambda';
import { NagSuppressions } from 'cdk-nag';
import type { Construct } from 'constructs';
import { BlogWorkflow } from '../constructs/blog-workflow.js';
import type { BaseStackProps } from './stack-props.js';

/** Props for {@link WorkflowStack}. */
export interface WorkflowStackProps extends BaseStackProps {
  /** The citation-tracker Lambda (from the ComputeStack). */
  readonly citationTracker: lambda.IFunction;
  /** The patch-applier Lambda (from the ComputeStack). */
  readonly patchApplier: lambda.IFunction;
  /** The promoter Lambda (from the ComputeStack). */
  readonly promoter: lambda.IFunction;
}

/**
 * WorkflowStack — the GEO feedback-loop Step Function.
 *
 * Owns the `geo-demo-dev-feedback-loop` Standard state machine (via the
 * {@link BlogWorkflow} construct) that orchestrates the three worker Lambdas.
 * Depends on the ComputeStack for those functions.
 */
export class WorkflowStack extends Stack {
  private readonly blogWorkflow: BlogWorkflow;

  constructor(scope: Construct, id: string, props: WorkflowStackProps) {
    super(scope, id, props);

    const { config, citationTracker, patchApplier, promoter } = props;

    this.blogWorkflow = new BlogWorkflow(this, 'Workflow', {
      prefix: config.prefix,
      workflow: config.workflow,
      citationTracker,
      patchApplier,
      promoter,
    });

    new CfnOutput(this, 'StateMachineArn', {
      value: this.blogWorkflow.stateMachine.stateMachineArn,
      description: 'ARN of the GEO feedback-loop state machine',
      exportName: `${config.prefix}-feedback-loop-arn`,
    });

    // cdk-nag: the state machine role uses scoped lambda:InvokeFunction grants
    // (and their :* version qualifiers) generated by the LambdaInvoke tasks.
    NagSuppressions.addStackSuppressions(this, [
      {
        id: 'AwsSolutions-IAM5',
        reason:
          'The state machine role is granted lambda:InvokeFunction on exactly ' +
          'the three worker functions; CDK adds the :* version-qualifier form of ' +
          'each function ARN, which is expected for LambdaInvoke tasks.',
      },
    ]);
  }

  /** The feedback-loop state machine ARN. */
  public get stateMachineArn(): string {
    return this.blogWorkflow.stateMachine.stateMachineArn;
  }
}
